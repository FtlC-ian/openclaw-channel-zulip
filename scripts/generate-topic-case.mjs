import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const sources = {
  "UnicodeData.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
  "SpecialCasing.txt": "8d5de354eef79f2395a54c9c7dcebbaf3d30fc962d0f85611ea97aa973a0c451",
  "DerivedCoreProperties.txt": "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd",
};
const sourceBaseUrl = "https://www.unicode.org/Public/16.0.0/ucd/";
const root = fileURLToPath(new URL("../", import.meta.url));
const outputPath = path.join(root, "src/zulip/topic-case-data.ts");
const { values } = parseArgs({ options: { "source-dir": { type: "string" }, check: { type: "boolean" } } });
if (!values["source-dir"]) {
  throw new Error("Usage: node scripts/generate-topic-case.mjs --source-dir /path/to/ucd-16.0.0 [--check]");
}

const inputs = {};
for (const [name, expectedHash] of Object.entries(sources)) {
  const bytes = await readFile(path.join(values["source-dir"], name));
  if (createHash("sha256").update(bytes).digest("hex") !== expectedHash) {
    throw new Error(`Unicode 16.0.0 SHA-256 mismatch: ${name} (${sourceBaseUrl}${name})`);
  }
  inputs[name] = bytes.toString("utf8");
}

const lowercase = new Map();
for (const line of inputs["UnicodeData.txt"].trim().split("\n")) {
  const fields = line.split(";");
  if (fields[13]) {
    lowercase.set(parseInt(fields[0], 16), String.fromCodePoint(parseInt(fields[13], 16)));
  }
}
let hasFinalSigma = false;
for (const line of inputs["SpecialCasing.txt"].split("\n")) {
  const fields = line.split("#")[0].trim().split(";").map((field) => field.trim());
  if (fields.length < 5) continue;
  const condition = fields[4];
  if (!condition) {
    lowercase.set(parseInt(fields[0], 16), String.fromCodePoint(...fields[1].split(/\s+/).map((cp) => parseInt(cp, 16))));
  } else if (condition === "Final_Sigma" && fields[0] === "03A3" && fields[1] === "03C2") {
    hasFinalSigma = true;
  } else if (!/^(lt|tr|az)( |$)/.test(condition)) {
    throw new Error(`Unsupported language-independent casing condition: ${condition}`);
  }
}
if (!hasFinalSigma) throw new Error("Missing Final_Sigma definition");
for (const [codePoint, value] of lowercase) {
  if (value === String.fromCodePoint(codePoint)) lowercase.delete(codePoint);
}

function propertyRanges(property) {
  const ranges = inputs["DerivedCoreProperties.txt"].split("\n").flatMap((line) => {
    const [range, name] = line.split("#")[0].trim().split(";").map((field) => field.trim());
    if (name !== property) return [];
    const [start, end = start] = range.split("..").map((cp) => parseInt(cp, 16));
    return [[start, end]];
  }).sort((a, b) => a[0] - b[0]);
  const merged = [];
  for (const [start, end] of ranges) {
    const previous = merged.at(-1);
    if (previous && start <= previous[1] + 1) previous[1] = Math.max(previous[1], end);
    else merged.push([start, end]);
  }
  return merged;
}

function linesOf(entries, width) {
  return Array.from({ length: Math.ceil(entries.length / width) }, (_, index) =>
    `  ${entries.slice(index * width, (index + 1) * width).join(", ")},`,
  ).join("\n");
}
const notice = await readFile(path.join(root, "docs/UNICODE-NOTICE.txt"), "utf8");
const license = notice.slice(notice.indexOf("UNICODE LICENSE V3")).trim();
const mappings = [...lowercase].sort((a, b) => a[0] - b[0]);
const properties = [["CASED_RANGES", "Cased"], ["CASE_IGNORABLE_RANGES", "Case_Ignorable"]];
const generated = [
  "// Generated by scripts/generate-topic-case.mjs from pinned Unicode 16.0.0 UCD.",
  `// Sources: ${sourceBaseUrl}{${Object.keys(sources).join(",")}}`,
  "/*\n" + license + "\n*/",
  "export const LOWERCASE_MAPPINGS: Readonly<Record<number, string>> = {",
  linesOf(mappings.map(([codePoint, value]) => `${codePoint}: ${JSON.stringify(value)}`), 6),
  "};",
  ...properties.flatMap(([constant, property]) => [
    `export const ${constant}: readonly number[] = [`,
    linesOf(propertyRanges(property).map(([start, end]) => `${start}, ${end}`), 6),
    "];",
  ]),
  "",
].join("\n");

if (values.check) {
  if (await readFile(outputPath, "utf8") !== generated) {
    throw new Error("topic-case-data.ts does not match the pinned Unicode 16.0.0 sources");
  }
  console.log("Unicode 16.0.0 generated data matches all pinned sources");
} else {
  await writeFile(outputPath, generated);
  console.log(`Generated ${mappings.length} lowercase mappings in ${Buffer.byteLength(generated)} bytes`);
}
